// Textures pixel art générées par code (aucun fichier image requis).

import * as THREE from 'three';
import { mulberry32 } from './noise.js';

function canvasTexture(canvas, { mipmaps = true, repeat = true } = {}) {
  const tex = new THREE.CanvasTexture(canvas);
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = mipmaps ? THREE.NearestMipmapLinearFilter : THREE.NearestFilter;
  tex.generateMipmaps = mipmaps;
  tex.colorSpace = THREE.SRGBColorSpace;
  if (repeat) tex.wrapS = tex.wrapT = THREE.RepeatWrapping;
  return tex;
}

// Grain doux pour le sol : quelques pixels plus sombres, petites touffes.
export function makeGrainTexture(seed = 7) {
  const size = 16;
  const c = document.createElement('canvas');
  c.width = c.height = size;
  const ctx = c.getContext('2d');
  const img = ctx.createImageData(size, size);
  const rand = mulberry32(seed);
  const set = (x, y, v) => {
    const o = (((y + size) % size) * size + ((x + size) % size)) * 4;
    img.data[o] = img.data[o + 1] = img.data[o + 2] = v;
    img.data[o + 3] = 255;
  };
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const r = rand();
      set(x, y, r < 0.6 ? 255 : r < 0.88 ? 238 : 224);
    }
  }
  // petits traits verticaux évoquant des brins
  for (let i = 0; i < 7; i++) {
    const x = Math.floor(rand() * size), y = Math.floor(rand() * size);
    set(x, y, 214);
    set(x, y + 1, 222);
  }
  ctx.putImageData(img, 0, 0);
  return canvasTexture(c);
}

// Motif de feuillage/écorce : taches claires et ombres douces.
export function makeLeafTexture(seed = 11) {
  const size = 16;
  const c = document.createElement('canvas');
  c.width = c.height = size;
  const ctx = c.getContext('2d');
  ctx.fillStyle = 'rgb(236,236,236)';
  ctx.fillRect(0, 0, size, size);
  const rand = mulberry32(seed);
  for (let i = 0; i < 22; i++) {
    const x = Math.floor(rand() * size), y = Math.floor(rand() * size);
    const light = rand() < 0.45;
    ctx.fillStyle = light ? 'rgb(255,255,255)' : 'rgb(206,206,206)';
    ctx.fillRect(x, y, 2, 1);
    ctx.fillRect(x + (light ? 0 : 1), y + 1, 1, 1);
  }
  return canvasTexture(c);
}


export const SPRITE = { GRASS: 0, TALL_GRASS: 1, PINK: 2, YELLOW: 3, DAISY: 4, LAVENDER: 5, MOONFLOWER: 6, MUSHROOM: 7 };
export const SPRITE_COUNT = SPRITES.length;

export function makeSpriteAtlas() {
  const T = 16;
  const c = document.createElement('canvas');
  c.width = T * SPRITES.length;
  c.height = T;
  const ctx = c.getContext('2d');
  const img = ctx.createImageData(c.width, T);
  SPRITES.forEach((src, idx) => {
    const rows = src.split('\n').filter((l) => l.length > 0);
    for (let y = 0; y < T; y++) {
      const row = (rows[y] || '').padEnd(T, '.');
      for (let x = 0; x < T; x++) {
        const col = PALETTE[row[x]];
        if (!col) continue;
        const o = (y * c.width + idx * T + x) * 4;
        img.data[o] = col[0]; img.data[o + 1] = col[1]; img.data[o + 2] = col[2]; img.data[o + 3] = 255;
      }
    }
  });
  ctx.putImageData(img, 0, 0);
  return canvasTexture(c, { mipmaps: false, repeat: false });
}
